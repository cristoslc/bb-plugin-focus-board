#!/usr/bin/env node
/**
 * Regenerates lib/unreleased-changelog.generated.ts from CHANGELOG.md's
 * "[Unreleased]" group. Wired into the "test" and "build" scripts so every
 * test run and every build embeds the current group — the dev board's
 * What's-new pulse tracks changelog edits with no manual regen step.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { parseUnreleasedChangelog } from "../lib/unreleased-changelog.ts";

const root = fileURLToPath(new URL("..", import.meta.url));
const markdown = readFileSync(`${root}/CHANGELOG.md`, "utf8");
const { items } = parseUnreleasedChangelog(markdown);

const source = `/** Generated by scripts/generate-unreleased.mjs from CHANGELOG.md — do not edit. */
export const UNRELEASED_ITEMS: readonly string[] = ${JSON.stringify(items, null, 2)};
`;

writeFileSync(`${root}/lib/unreleased-changelog.generated.ts`, source);